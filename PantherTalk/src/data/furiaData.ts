export function getRandomHistoryFact(lastFact: string | null = null): string {
  let randomIndex;
  let historyItem;
  
  // Keep generating a new random fact until we find one that's different from the last one
  do {
    randomIndex = Math.floor(Math.random() * furiaHistory.length);
    historyItem = furiaHistory[randomIndex];
  } while (lastFact && lastFact.includes(`${historyItem.year} - ${historyItem.title}`));
  
  return `📅 ${historyItem.year} - ${historyItem.title}: ${historyItem.description}`;
}

export function getRandomStats(lastStat: string | null = null): string {
  let randomIndex;
  let statItem;
  
  // Keep generating a new random stat until we find one that's different from the last one
  do {
    randomIndex = Math.floor(Math.random() * furiaStats.length);
    statItem = furiaStats[randomIndex];
  } while (lastStat && lastStat === statItem.content);
  
  return statItem.content;
}

export function getRandomQuizQuestions(count: number): QuizQuestion[] {
  const shuffled = [...quizQuestions].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

export function getRandomUniqueQuizQuestions(count: number): QuizQuestion[] {
  const availableQuestions = [...quizQuestions];
  const selectedQuestions: QuizQuestion[] = [];
  
  for (let i = 0; i < count && availableQuestions.length > 0; i++) {
    const randomIndex = Math.floor(Math.random() * availableQuestions.length);
    selectedQuestions.push(availableQuestions[randomIndex]);
    availableQuestions.splice(randomIndex, 1);
  }
  
  return selectedQuestions;
}

export function getRandomFact(): string {
  const randomIndex = Math.floor(Math.random() * randomFacts.length);
  return randomFacts[randomIndex];
}

export function getUniqueRandomFacts(count: number, previousFacts: string[] = []): string[] {
  const availableFacts = [...randomFacts].filter(fact => !previousFacts.includes(fact));
  const selectedFacts: string[] = [];
  
  // If all facts have been used previously or there are no available facts left,
  // reset the filter and use all facts again
  const factsPool = availableFacts.length > 0 ? availableFacts : [...randomFacts];
  
  for (let i = 0; i < count && factsPool.length > 0; i++) {
    const randomIndex = Math.floor(Math.random() * factsPool.length);
    selectedFacts.push(factsPool[randomIndex]);
    factsPool.splice(randomIndex, 1);
  }
  
  return selectedFacts;
}

